export const LANGS: { id: Lang; label: string }[] = [
  { id: "ar", label: "العربية" },
  { id: "en", label: "English" },
  { id: "he", label: "עברית" },
];

export const isRtl = (lang: Lang) => lang !== "en";

export type Translate = (key: I18nKey, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): Translate {
  const table = tables[lang] ?? en;
  return (key, vars) => {
    let s = table[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

/** Translate a raw HA state if we know it, otherwise return it unchanged. */
export function hasKey(key: string): key is I18nKey {
  return key in en;
}

